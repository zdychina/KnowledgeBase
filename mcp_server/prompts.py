"""MCP prompts — answer framework and guided response templates."""

from __future__ import annotations

SEMANTIC_RULES = """\
# 证据语义规则

## evidence_role 定义

- **direct_answer**: 最接近用户问题主答案的证据。优先信任。
- **support**: 支撑性证据，补充前置条件、参数、限制、步骤、注意事项。
- **contrast**: 对比性证据，解释差异、区分对象、比较方案。
- **background**: 背景性证据，只能帮助理解上下文，不能单独支撑高风险操作结论。
- **missing**: 相关但不足以支撑答案的信号，不应强行当有效答案证据使用。

## 优先信任规则

- 有 direct_answer 的条目优先
- 与当前 intent 匹配的 semantic_role 优先
- 多条证据互相印证、且来源一致或互补的内容优先

## 禁止行为

- 只因为分数高就下结论
- 把背景证据当成操作依据
- 用一条模糊片段支撑高风险回答
"""

ANSWER_FRAMEWORK = """\
# 回答框架

## answer_now（证据充分）

回答应包含：
1. 直接结论
2. 关键证据依据
3. 会影响结论成立的前提或限制
4. 必要时给出来源说明

## answer_with_caution（证据部分）

回答应包含：
1. 明确标注的保守结论或方向性判断
2. 当前最强证据
3. 缺失的假设、范围或证据
4. 如果要提高置信度，用户下一步需要补什么信息

## ask_followup（证据不足）

回答应包含：
1. 当前已有的线索（如有）
2. 明确告知证据不足以可靠回答
3. 具体追问（能缩小答案空间的问题）

## delegate（交给其他 Skill）

应把证据作为"输入"传给下游 Skill：
- 哪些是直接证据
- 哪些是支撑证据
- 哪些地方还有缺口

## 高风险操作类问题

必须显式输出：
- 结论
- 依据
- 前提/限制
- 不确定点
- 建议下一步
"""
